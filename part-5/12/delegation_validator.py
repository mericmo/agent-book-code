# delegation_validator.py
"""委派任务单的四要素校验：缺项不派发，而不是靠主管自觉。

早期版本的指令是「研究半导体短缺」，只写了目标，子代理就自己脑补。
修复方案是把四要素做成必填项，缺项在派发之前直接拦下。
"""

REQUIRED = ("目标", "输出格式", "工具与来源指引", "任务边界")


def validate(card):
    """返回缺失的要素；四项全齐时返回空列表。"""
    return [k for k in REQUIRED if not card.get(k)]


def dispatch(card):
    """派发前的守卫：缺项就拦，别让子代理拿半张任务单开工。"""
    missing = validate(card)
    if missing:
        return "拒绝派发：缺 " + "、".join(missing)
    return "派发：" + card["目标"]


# 早期版本：只写了目标
EARLY = {"目标": "研究半导体短缺"}
print("任务单 A：", dispatch(EARLY))

# 修复后：四要素齐全
FIXED = {
    "目标": "查 2025 年全球半导体短缺现状与主要瓶颈环节",
    "输出格式": "分环节的要点清单，每点附一手来源链接",
    "工具与来源指引": "优先一手报道与官方数据，禁用二手转述",
    "任务边界": "只覆盖 2025 年，不做 2021 年历史对比",
}
print("任务单 B：", dispatch(FIXED))

# 输出：
# 任务单 A： 拒绝派发：缺 输出格式、工具与来源指引、任务边界
# 任务单 B： 派发：查 2025 年全球半导体短缺现状与主要瓶颈环节